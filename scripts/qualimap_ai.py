"""
qualimap_ai.py -- parse Qualimap reports and add AI summaries via an OpenAI-compatible endpoint.

Discovers and annotates:
  1) Multi-sample BAM QC report (multisampleBamQcReport.html)
  2) Single-sample RNA-Seq QC reports (qualimapReport.html in rnaseqqc_results)
  3) Single-sample BAM QC reports (qualimapReport.html in bamqc_results)

The LLM is any OpenAI-compatible /v1/chat/completions endpoint (local vLLM, Ollama,
OpenAI, etc.). No endpoint or model is baked in -- you must supply them at runtime
via CLI flags or env vars (LLM_ENDPOINT, LLM_MODEL, LLM_API_KEY).
"""

