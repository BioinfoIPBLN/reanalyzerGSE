def process_multisample_report(cfg, html_path):
    llm_common.log(f"[Qualimap AI] Annotating multi-sample report: {html_path}")
    html_content, table_text = parse_multisample_html(html_path)
    if not table_text.strip():
        llm_common.log(f"[Qualimap AI] Warning: No table data found in {html_path}")
        return

    text, usage = ask_llm(cfg, SYS_PROMPT_MULTISAMPLE, table_text)
    if llm_common.is_degraded(text):
        llm_common.log(f"[Qualimap AI] Degraded response dropped for {html_path}")
        return

    summary_html = md_to_html(text)
    footer = ai_footer(cfg, usage, data_filename="multibamqc_results")
    html_content = inject_ai_box(html_content, summary_html, footer)

    # Process per-section AI summaries for multi-sample report
    for heading, metric_desc in MULTISAMPLE_SECTION_MAP.items():
        if re.search(r'<h2[^>]*>\s*' + re.escape(heading) + r'[^>]*>', html_content, re.IGNORECASE):
            try:
                sec_prompt = f"{SYS_PROMPT_SECTION}\nSection: {heading}\nMetric focus: {metric_desc}"
                sec_text, sec_usage = ask_llm(cfg, sec_prompt, table_text)
                if not llm_common.is_degraded(sec_text):
                    sec_body_html = md_to_html(sec_text)
                    sec_footer = ai_footer(cfg, sec_usage, data_filename=f"multibamqc_{heading.lower().replace(' ', '_')}")
                    html_content = inject_section_ai_box(html_content, heading, sec_body_html, sec_footer)
            except Exception as e:
                llm_common.log(f"[Qualimap AI] Section {heading} error for multi-sample report: {e}")

    with open(html_path, "w", encoding="utf-8") as fh:
        fh.write(html_content)
    llm_common.log(f"[Qualimap AI] Done multi-sample report: {html_path}")

