SYS_PROMPT_SECTION = "\n".join([
    "You are an expert bioinformatician evaluating a specific plot/section of a Qualimap report.",
    "Produce 1-2 concise bullet points summarizing key observations from the provided plot raw data.",
    "Use markdown. Highlight severity with directives like :span[value]{.text-red}, .text-orange, .text-yellow, .text-green if applicable.",
])

def inject_section_ai_box(html_content, heading_name, summary_body_html, footer_html):
    box_html = (
        f'\n<div class="ai-summary-box-section" style="background-color: #f8f9fa; border-left: 3px solid #17a2b8; '
        f'padding: 8px 12px; margin: 10px 0; border-radius: 4px; font-family: sans-serif; font-size: 0.9em;">\n'
        f'  <div class="ai-summary-content" style="color: #333;">\n{summary_body_html}\n  </div>\n'
        f'  {footer_html}\n'
        f'</div>\n'
    )
    pattern = r'(<h2[^>]*>\s*' + re.escape(heading_name) + r'[^>]*>.*?</h2>)'
    match = re.search(pattern, html_content, re.IGNORECASE)
    if match:
        snippet_after = html_content[match.end():match.end()+250]
        if 'ai-summary-box' in snippet_after or 'ai-summary-box-section' in snippet_after:
            return html_content
        return re.sub(pattern, r'\1' + box_html, html_content, count=1, flags=re.IGNORECASE)
    return html_content

def process_single_sample_report(cfg, html_path, report_type):
    report_dir = os.path.dirname(html_path)
    sample_name = os.path.basename(report_dir)
    llm_common.log(f"[Qualimap AI] Annotating {report_type} report for {sample_name}: {html_path}")

    if report_type == "rnaseq":
        html_content, text_data = parse_rnaseq_qc(report_dir, html_path)
        sys_prompt = SYS_PROMPT_RNASEQ
        parsed_name = "rnaseq_qc_results.txt"
    else:
        html_content, text_data = parse_bam_qc(report_dir, html_path)
        sys_prompt = SYS_PROMPT_BAMQC
        parsed_name = "genome_results.txt"

    if not text_data.strip():
        llm_common.log(f"[Qualimap AI] Warning: No text data for {sample_name}")
        return

    text, usage = ask_llm(cfg, sys_prompt, text_data)
    if llm_common.is_degraded(text):
        llm_common.log(f"[Qualimap AI] Degraded response dropped for {sample_name}")
        return

    summary_html = md_to_html(text)
    footer = ai_footer(cfg, usage, data_filename=parsed_name)
    html_content = inject_ai_box(html_content, summary_html, footer)

    # Process per-section raw data tables from raw_data_qualimapReport directory
    raw_data_dir = os.path.join(report_dir, "raw_data_qualimapReport")
    if os.path.isdir(raw_data_dir):
        for fname, heading in SECTION_MAP.items():
            fpath = os.path.join(raw_data_dir, fname)
            if not os.path.exists(fpath):
                continue
            try:
                with open(fpath, encoding="utf-8", errors="replace") as fh:
                    raw_text = fh.read().strip()
                if not raw_text:
                    continue
                # Cap large raw histogram files (e.g. coverage_histogram.txt 400KB+) to max 100 lines
                lines = [l for l in raw_text.splitlines() if l.strip()]
                if len(lines) > 100:
                    raw_text = "\n".join(lines[:50] + ["\n... [middle histogram data points omitted] ...\n"] + lines[-50:])
                sec_text, sec_usage = ask_llm(cfg, f"{SYS_PROMPT_SECTION}\nSection: {heading}\nSample: {sample_name}", raw_text)
                if not llm_common.is_degraded(sec_text):
                    sec_body_html = md_to_html(sec_text)
                    sec_footer = ai_footer(cfg, sec_usage, data_filename=fname)
                    html_content = inject_section_ai_box(html_content, heading, sec_body_html, sec_footer)
            except Exception as e:
                llm_common.log(f"[Qualimap AI] Section {fname} error for {sample_name}: {e}")

    with open(html_path, "w", encoding="utf-8") as fh:
        fh.write(html_content)
    llm_common.log(f"[Qualimap AI] Done {sample_name}")

def main():
    p = argparse.ArgumentParser(description="Qualimap AI annotation script.")
    p.add_argument("--analysis-dir", required=True, help="Root directory containing Qualimap reports.")
    p.add_argument("--llm-endpoint", default=DEF_ENDPOINT, help="OpenAI-compatible URL")
    p.add_argument("--llm-model", default=DEF_MODEL, help="Model name")
    p.add_argument("--llm-api-key", default=DEF_API_KEY, help="API key")
    p.add_argument("--llm-context-window", type=int, default=DEF_CONTEXT_WINDOW)
    p.add_argument("--llm-timeout", type=int, default=DEF_TIMEOUT)
    args = p.parse_args()

    if not args.llm_endpoint or not args.llm_model:
        llm_common.log("[Qualimap AI] LLM_ENDPOINT and LLM_MODEL must be supplied. Exiting without changes.")
        sys.exit(0)

    cfg = args
    analysis_dir = os.path.abspath(args.analysis_dir)

    multi_reports = []
    single_rnaseq_reports = []
    single_bam_reports = []

    for root, dirs, files in os.walk(analysis_dir):
        for f in files:
            full = os.path.join(root, f)
            if f == "multisampleBamQcReport.html":
                multi_reports.append(full)
            elif f == "qualimapReport.html":
                root_low = root.lower()
                if os.path.exists(os.path.join(root, "rnaseq_qc_results.txt")) or "rnaseq" in root_low:
                    single_rnaseq_reports.append(full)
                elif os.path.exists(os.path.join(root, "genome_results.txt")) or "bam" in root_low:
                    single_bam_reports.append(full)
                else:
                    single_rnaseq_reports.append(full)

    secrets = llm_common.secret_values(endpoint=cfg.llm_endpoint, api_key=cfg.llm_api_key)

    try:
        # Process Multi-sample report first
        for m_rep in multi_reports:
            try:
                process_multisample_report(cfg, m_rep)
                llm_common.scrub_file(m_rep, secrets)
            except llm_common.LLMTimeout:
                llm_common.log(f"[Qualimap AI] Timeout processing {m_rep}")

        # Process single-sample RNA-Seq reports
        for r_rep in single_rnaseq_reports:
            try:
                process_single_sample_report(cfg, r_rep, "rnaseq")
                llm_common.scrub_file(r_rep, secrets)
            except llm_common.LLMTimeout:
                llm_common.log(f"[Qualimap AI] Timeout processing {r_rep}")

        # Process single-sample BAM reports
        for b_rep in single_bam_reports:
            try:
                process_single_sample_report(cfg, b_rep, "bamqc")
                llm_common.scrub_file(b_rep, secrets)
            except llm_common.LLMTimeout:
                llm_common.log(f"[Qualimap AI] Timeout processing {b_rep}")

    except Exception as e:
        llm_common.log(f"[Qualimap AI] Error during AI pass: {e}")

if __name__ == "__main__":
    main()
